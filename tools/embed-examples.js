// Copies examples/*.py, and what each prints (examples/output/*.txt, recorded by
// tools/record-outputs.py), into src/examples.js, so the page can show them from file://
// (a browser will not fetch local files). Run: node tools/embed-examples.js
// `make test` fails when src/examples.js is out of date.
const fs = require('fs');
const path = require('path');

const root = path.resolve(__dirname, '..');

function build() {
    const qiskit = fs.readFileSync(path.join(root, 'requirements.txt'), 'utf8').match(/^qiskit==(\S+)/m)[1];
    const dir = path.join(root, 'examples');
    const files = fs.readdirSync(dir).filter(f => /^\d\d_.*\.py$/.test(f)).sort();
    const out = {};
    for (const f of files) {
        const name = f.replace(/\.py$/, ''), rec = path.join(dir, 'output', name + '.txt');
        out[name] = {file: 'examples/' + f, code: fs.readFileSync(path.join(dir, f), 'utf8'),
            output: fs.existsSync(rec) ? fs.readFileSync(rec, 'utf8') : null};
    }
    return '// Generated by tools/embed-examples.js from examples/*.py. Do not edit.\n' +
        'var QQ = globalThis.QQ || (globalThis.QQ = {});\n' +
        'QQ.EXAMPLES = ' + JSON.stringify(out, null, 1) + ';\n' +
        `QQ.QISKIT_VERSION = '${qiskit}'; // from requirements.txt, the version the outputs come from\n`;
}

module.exports = build;
if (require.main === module) {
    fs.writeFileSync(path.join(root, 'src', 'examples.js'), build());
    console.log('src/examples.js written');
}
